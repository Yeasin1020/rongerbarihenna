/**
 * `npm run dev` er age nijei chole (predev). Kono package lage na.
 *
 *  1. Node version check
 *  2. .env na thakle database URL chay, baki sob (secret, admin password) nijei banay
 *  3. node_modules na thakle npm install
 *  4. Database e table banay (schema change hole abar), demo product boshay
 *
 * Ekbar sob hoye gele porer bar kichui kore na — sathe sathe website chalu hoy.
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import { createInterface } from 'node:readline/promises';
import { join } from 'node:path';

const ROOT = process.cwd();
const ENV = join(ROOT, '.env');
const STATE = join(ROOT, '.rbh-setup.json');
const isWin = process.platform === 'win32';

const c = {
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
};
const step = (s) => console.log(`\n${c.green('●')} ${c.bold(s)}`);

function fail(msg) {
  console.error(`\n${c.red('✖')} ${msg}\n${c.dim('Upore je lekha ta ashche seta copy kore Claude ke pathao.')}\n`);
  process.exit(1);
}

function run(cmd, args) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', shell: isWin, cwd: ROOT, env: process.env });
  return r.status === 0;
}

// ---------- 1. Node ----------
const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 18 || (major === 18 && minor < 18)) {
  fail(`Node.js ${process.versions.node} purono. https://nodejs.org theke LTS (20 ba 22) install koro.`);
}

// ---------- 2. .env ----------
function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}

/** Neon URL theke pooled (website) ar direct (table banano) duita URL banay */
function neonUrls(input) {
  const u = new URL(input.trim().replace(/^psql\s+/, '').replace(/^['"]|['"]$/g, ''));
  if (!/^postgres(ql)?:$/.test(u.protocol)) throw new Error('postgresql:// diye shuru hote hobe');
  u.searchParams.delete('channel_binding'); // Prisma er sathe jhamela kore
  if (!u.searchParams.get('sslmode')) u.searchParams.set('sslmode', 'require');
  if (!u.searchParams.get('connect_timeout')) u.searchParams.set('connect_timeout', '15');

  const pooled = new URL(u);
  const direct = new URL(u);
  const [first, ...rest] = u.hostname.split('.');
  if (u.hostname.includes('neon.tech')) {
    const base = first.replace(/-pooler$/, '');
    pooled.hostname = [`${base}-pooler`, ...rest].join('.');
    direct.hostname = [base, ...rest].join('.');
  }
  return { pooled: pooled.toString(), direct: direct.toString() };
}

async function ensureEnv() {
  let env = existsSync(ENV) ? parseEnv(readFileSync(ENV, 'utf8')) : {};

  if (!env.DATABASE_URL) {
    step('Database connect korte hobe (shudhu prothom bar)');
    console.log(c.dim('  Neon dashboard > Connect > connection string copy kore ekhane paste koro, tarpor Enter.'));
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    let urls;
    while (!urls) {
      const ans = await rl.question(c.yellow('  Database URL: '));
      try {
        urls = neonUrls(ans);
      } catch (e) {
        console.log(c.red(`  Ei URL ta thik na (${e.message}). Abar paste koro.`));
      }
    }
    rl.close();

    const adminPassword = randomBytes(9).toString('base64url');
    const content = `# Auto-generated by scripts/setup.mjs — ei file kauke dekhabe na, GitHub e jabe na

# Neon PostgreSQL
DATABASE_URL="${urls.pooled}"
DIRECT_URL="${urls.direct}"

# Website
NEXT_PUBLIC_SITE_URL=http://localhost:3000

# Security (random banano)
JWT_SECRET=${randomBytes(36).toString('base64url')}

# Admin login (chaile bodlao — prothom login er age)
ADMIN_EMAIL=admin@rongerbari.com
ADMIN_PASSWORD=${adminPassword}
`;
    writeFileSync(ENV, content);
    env = parseEnv(content);
    console.log(c.green('  ✔ .env file toiri holo'));
    console.log(`\n  ${c.bold('Admin login (likhe rakho):')}\n  Email:    ${c.yellow(env.ADMIN_EMAIL)}\n  Password: ${c.yellow(adminPassword)}\n`);
    return;
  }

  // Purono .env e DIRECT_URL na thakle jog kori
  if (!env.DIRECT_URL || !env.JWT_SECRET) {
    let text = readFileSync(ENV, 'utf8');
    if (!env.DIRECT_URL) {
      const { direct } = neonUrls(env.DATABASE_URL);
      text += `\nDIRECT_URL="${direct}"\n`;
    }
    if (!env.JWT_SECRET) text += `\nJWT_SECRET=${randomBytes(36).toString('base64url')}\n`;
    writeFileSync(ENV, text);
    console.log(c.green('✔ .env update holo'));
  }
}

// ---------- main ----------
await ensureEnv();

const state = existsSync(STATE) ? JSON.parse(readFileSync(STATE, 'utf8')) : {};
const pkgHash = createHash('sha1').update(readFileSync(join(ROOT, 'package.json'))).digest('hex');
const schemaHash = createHash('sha1').update(readFileSync(join(ROOT, 'prisma', 'schema.prisma'))).digest('hex');
const nextBin = join(ROOT, 'node_modules', '.bin', isWin ? 'next.cmd' : 'next');

if (!existsSync(nextBin) || state.pkgHash !== pkgHash) {
  step('Package install hocche (prothom bar 2-5 minute lagte pare)...');
  if (!run('npm', ['install', '--no-audit', '--no-fund'])) fail('npm install hoy ni. Internet connection dekho.');
  state.pkgHash = pkgHash;
  writeFileSync(STATE, JSON.stringify(state, null, 2));
}

if (state.schemaHash !== schemaHash) {
  step('Database e table banano hocche...');
  if (!run('npx', ['prisma', 'db', 'push'])) {
    fail('Database e connect kora jay ni. .env er DATABASE_URL thik ache kina dekho. Neon ghumiye thakle 20 second por abar `npm run dev` dao.');
  }
  step('Demo product boshano hocche...');
  if (!run('npx', ['tsx', 'prisma/seed.ts'])) fail('Demo data boshano jay ni.');
  state.schemaHash = schemaHash;
  writeFileSync(STATE, JSON.stringify(state, null, 2));
}

// ---------- Gallery chobi Cloudinary te (ekbar) ----------
if (!state.galleryImported && existsSync(join(ROOT, 'public', 'gallery'))) {
  const e = parseEnv(readFileSync(ENV, 'utf8'));
  const hasCloud = e.CLOUDINARY_URL || (e.CLOUDINARY_CLOUD_NAME && e.CLOUDINARY_API_KEY && e.CLOUDINARY_API_SECRET);
  if (!hasCloud) {
    console.log(c.dim('\n  Gallery: chobi website theke-i dekhabe. .env e Cloudinary dile porer bar Cloudinary te chole jabe.'));
  } else {
    step('Gallery er chobi Cloudinary te upload hocche (ekbar-i)...');
    const r = spawnSync('npx', ['tsx', 'prisma/import-gallery.ts'], { stdio: 'inherit', shell: isWin, cwd: ROOT });
    if (r.status === 0) {
      state.galleryImported = true;
      writeFileSync(STATE, JSON.stringify(state, null, 2));
      // Purono cache muche dei jeno notun gallery sathe sathe dekhay
      rmSync(join(ROOT, '.next', 'cache', 'fetch-cache'), { recursive: true, force: true });
    } else {
      console.log(c.yellow('  Gallery upload hoy ni — website tobuo cholbe. Upore error ta Claude ke pathao.'));
    }
  }
}

// Dev shuru hole purono data cache muche dei — admin/code er change sathe sathe dekhay
rmSync(join(ROOT, '.next', 'cache', 'fetch-cache'), { recursive: true, force: true });

const env = parseEnv(readFileSync(ENV, 'utf8'));
console.log(`
${c.green('✔ Sob ready!')}
  Website: ${c.bold('http://localhost:3000')}
  Admin:   ${c.bold('http://localhost:3000/admin')}  ${c.dim(`(${env.ADMIN_EMAIL || ''})`)}
`);
